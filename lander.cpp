/**
 * @brief Handle key down events — shared game state machine logic
 * Called from WindowProc on Windows and keyDown: on macOS
 */
void HandleKeyDown(int vk) {
    switch (gameState) {
        case GameState::TITLE_SCREEN:
            if (vk == VK_SPACE) {
                InitGame();
                PlaySound_MenuSelect();
            } else if (vk == 'H') {
                gameState = GameState::HIGH_SCORES;
                PlaySound_MenuSelect();
            } else if (vk == 'S') {
                gameState = GameState::SETTINGS;
                PlaySound_MenuSelect();
            } else if (vk == 'Q') {
                HandleQuit();
            }
            break;

        case GameState::GAME_OVER:
            if (vk == VK_SPACE) {
                InitGame();
                PlaySound_MenuSelect();
            } else if (vk == 'Q') {
                HandleQuit();
            } else if (vk == 'R') {
                InitGame();
                PlaySound_MenuSelect();
            }
            break;

        case GameState::HIGH_SCORES:
            if (vk == VK_ESCAPE) {
                gameState = GameState::TITLE_SCREEN;
                InitBackgroundLanders();
                PlaySound_MenuSelect();
            } else if (vk == 'Q') {
                HandleQuit();
            }
            break;

        case GameState::ENTER_NAME:
            if (vk == VK_RETURN && nameLength > 0) {
                UpdateHighScores(score, level);
                gameState = GameState::HIGH_SCORES;
                PlaySound_MenuSelect();
            } else if (vk == VK_BACK && nameLength > 0) {
                nameLength--;
                playerName[nameLength] = '\0';
            }
            break;

        case GameState::PLAYING:
            if (vk == VK_ESCAPE) {
                gameState = GameState::TITLE_SCREEN;
                InitBackgroundLanders();
                StopSound_Thrust();
            } else if (vk == 'P') {
                gameState = GameState::PAUSED;
            } else if (vk == 'Q') {
                previousState = gameState;
                confirmMode = ConfirmMode::QUIT;
                gameState = GameState::CONFIRM_QUIT;
                StopSound_Thrust();
                PlaySound_MenuSelect();
            } else if (vk == 'R') {
                previousState = gameState;
                confirmMode = ConfirmMode::RESTART;
                gameState = GameState::CONFIRM_QUIT;
                StopSound_Thrust();
                PlaySound_MenuSelect();
            }
            break;

        case GameState::PAUSED:
            if (vk == 'P' || vk == VK_ESCAPE) {
                gameState = GameState::PLAYING;
            } else if (vk == 'Q') {
                previousState = gameState;
                confirmMode = ConfirmMode::QUIT;
                gameState = GameState::CONFIRM_QUIT;
                PlaySound_MenuSelect();
            } else if (vk == 'R') {
                previousState = gameState;
                confirmMode = ConfirmMode::RESTART;
                gameState = GameState::CONFIRM_QUIT;
                PlaySound_MenuSelect();
            }
            break;

        case GameState::CONFIRM_QUIT:
            if (vk == VK_ESCAPE) {
                gameState = previousState;
                PlaySound_MenuSelect();
            } else if (vk == 'Q') {
                HandleQuit();
            } else if (vk == 'R') {
                InitGame();
                PlaySound_MenuSelect();
            }
            break;

        case GameState::SETTINGS: {
            float settingSteps[] = { 0.01f, 0.01f, 0.01f, 10.0f, 0.1f };
            float settingMins[] = { 0.01f, 0.01f, 0.01f, 10.0f, 0.5f };
            float settingMaxs[] = { 0.20f, 0.30f, 0.20f, 500.0f, 5.0f };
            float* settingValues[] = {
                &settings.gravity,
                &settings.thrustPower,
                &settings.sideThrustPower,
                &settings.initialFuel,
                &settings.safeLandingSpeed
            };

            if (vk == VK_ESCAPE) {
                SaveSettings();
                gameState = GameState::TITLE_SCREEN;
                InitBackgroundLanders();
                PlaySound_MenuSelect();
            } else if (vk == VK_UP) {
                settings.selectedOption = (settings.selectedOption - 1 + 5) % 5;
                PlaySound_MenuSelect();
            } else if (vk == VK_DOWN) {
                settings.selectedOption = (settings.selectedOption + 1) % 5;
                PlaySound_MenuSelect();
            } else if (vk == VK_LEFT) {
                int opt = settings.selectedOption;
                *settingValues[opt] -= settingSteps[opt];
                if (*settingValues[opt] < settingMins[opt]) {
                    *settingValues[opt] = settingMins[opt];
                }
                SaveSettings();
            } else if (vk == VK_RIGHT) {
                int opt = settings.selectedOption;
                *settingValues[opt] += settingSteps[opt];
                if (*settingValues[opt] > settingMaxs[opt]) {
                    *settingValues[opt] = settingMaxs[opt];
                }
                SaveSettings();
            } else if (vk == 'R') {
                ResetSettings();
                PlaySound_MenuSelect();
            }
            break;
        }

        default:
            break;
    }
}

