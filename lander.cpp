    if (!g_platCtx.cgCtx) {
        int bytesPerRow = WINDOW_WIDTH * 4;
        g_platCtx.bitmapData = calloc(WINDOW_HEIGHT, bytesPerRow);
        CGColorSpaceRef colorSpace = CGColorSpaceCreateDeviceRGB();
        g_platCtx.cgCtx = CGBitmapContextCreate(
            g_platCtx.bitmapData, WINDOW_WIDTH, WINDOW_HEIGHT, 8, bytesPerRow,
            colorSpace, kCGImageAlphaPremultipliedFirst | kCGBitmapByteOrder32Little);
        CGColorSpaceRelease(colorSpace);

        // Flip Y so Y=0 is at top (matches Windows convention)
        CGContextTranslateCTM(g_platCtx.cgCtx, 0, WINDOW_HEIGHT);
        CGContextScaleCTM(g_platCtx.cgCtx, 1, -1);
    }
