// No-op callback for one-shot AudioQueue playback
static void MacBeepCallback(void* /*userData*/, AudioQueueRef /*queue*/,
                            AudioQueueBufferRef /*buffer*/) {}

/**
 * @brief Synchronous beep at specified frequency and duration (replaces Windows Beep())
 */
static void MacBeep(int freq, int durationMs) {
    const int sampleRate = 22050;
    int numSamples = sampleRate * durationMs / 1000;
    if (numSamples <= 0) return;

    AudioStreamBasicDescription desc = {};
    desc.mSampleRate = sampleRate;
    desc.mFormatID = kAudioFormatLinearPCM;
    desc.mFormatFlags = kLinearPCMFormatFlagIsSignedInteger | kLinearPCMFormatFlagIsPacked;
    desc.mBitsPerChannel = 16;
    desc.mChannelsPerFrame = 1;
    desc.mBytesPerFrame = 2;
    desc.mFramesPerPacket = 1;
    desc.mBytesPerPacket = 2;

    AudioQueueRef queue = nullptr;
    if (AudioQueueNewOutput(&desc, MacBeepCallback, nullptr, nullptr, nullptr, 0, &queue) != noErr) return;

    AudioQueueBufferRef buffer = nullptr;
    UInt32 bufSize = numSamples * sizeof(short);
    if (AudioQueueAllocateBuffer(queue, bufSize, &buffer) != noErr) {
        AudioQueueDispose(queue, true);
        return;
    }

    short* samples = (short*)buffer->mAudioData;
    for (int i = 0; i < numSamples; i++) {
        samples[i] = static_cast<short>(sin(2.0 * M_PI * freq * i / sampleRate) * 16000);
    }
    buffer->mAudioDataByteSize = bufSize;

    AudioQueueEnqueueBuffer(queue, buffer, 0, nullptr);
    AudioQueueStart(queue, nullptr);

    std::this_thread::sleep_for(std::chrono::milliseconds(durationMs + 50));

    AudioQueueStop(queue, true);
    AudioQueueDispose(queue, true);
}

bool InitAudio() {
    soundInitialized = true;
    return true;
}

void CleanupAudio() {
    soundInitialized = false;
}

// AudioQueue callback for continuous thrust sound streaming
static void ThrustAudioCallback(void* /*userData*/, AudioQueueRef queue,
                                AudioQueueBufferRef buffer) {
    if (!thrustSoundActive) return;

    int numSamples = buffer->mAudioDataByteSize / sizeof(short);
    GenerateRocketSound((short*)buffer->mAudioData, numSamples);
    AudioQueueEnqueueBuffer(queue, buffer, 0, nullptr);
}

void ThrustSoundThreadProc() {
    AudioStreamBasicDescription desc = {};
    desc.mSampleRate = 22050;
    desc.mFormatID = kAudioFormatLinearPCM;
    desc.mFormatFlags = kLinearPCMFormatFlagIsSignedInteger | kLinearPCMFormatFlagIsPacked;
    desc.mBitsPerChannel = 16;
    desc.mChannelsPerFrame = 1;
    desc.mBytesPerFrame = 2;
    desc.mFramesPerPacket = 1;
    desc.mBytesPerPacket = 2;

    AudioQueueRef queue = nullptr;
    if (AudioQueueNewOutput(&desc, ThrustAudioCallback, nullptr, nullptr, nullptr, 0, &queue) != noErr) return;

    const int bufferSize = 4410;  // 0.2 seconds at 22050 Hz
    for (int i = 0; i < 2; i++) {
        AudioQueueBufferRef buf;
        AudioQueueAllocateBuffer(queue, bufferSize * sizeof(short), &buf);
        buf->mAudioDataByteSize = bufferSize * sizeof(short);
        GenerateRocketSound((short*)buf->mAudioData, bufferSize);
        AudioQueueEnqueueBuffer(queue, buf, 0, nullptr);
    }

    AudioQueueStart(queue, nullptr);

    while (thrustSoundActive) {
        std::this_thread::sleep_for(std::chrono::milliseconds(50));
    }

    AudioQueueStop(queue, true);
    AudioQueueDispose(queue, true);
}

void PlaySound_Thrust() {
    // Atomic false->true transition guards against spawning two threads.
    bool expected = false;
    if (thrustSoundActive.compare_exchange_strong(expected, true)) {
        // A prior thread must be fully joined before reassigning (assigning to
        // a joinable std::thread calls std::terminate).
        if (thrustSoundThread.joinable()) {
            thrustSoundThread.join();
        }
        thrustSoundThread = std::thread(ThrustSoundThreadProc);
    }
}

void StopSound_Thrust() {
    // Atomic true->false transition ensures exactly one caller joins the thread.
    bool expected = true;
    if (thrustSoundActive.compare_exchange_strong(expected, false)) {
        if (thrustSoundThread.joinable()) {
            thrustSoundThread.join();
        }
    }
}

/**
 * @brief Worker that synthesizes and plays the explosion (blocks until done).
 * Runs on a detached thread so it never stalls the game/UI thread.
 */
void CrashSoundThreadProc() {
    const int sampleRate = 22050;
    const int bufferSize = sampleRate;  // 1 second explosion

    AudioStreamBasicDescription desc = {};
    desc.mSampleRate = sampleRate;
    desc.mFormatID = kAudioFormatLinearPCM;
    desc.mFormatFlags = kLinearPCMFormatFlagIsSignedInteger | kLinearPCMFormatFlagIsPacked;
    desc.mBitsPerChannel = 16;
    desc.mChannelsPerFrame = 1;
    desc.mBytesPerFrame = 2;
    desc.mFramesPerPacket = 1;
    desc.mBytesPerPacket = 2;

    AudioQueueRef queue = nullptr;
    if (AudioQueueNewOutput(&desc, MacBeepCallback, nullptr, nullptr, nullptr, 0, &queue) != noErr) return;

    AudioQueueBufferRef buffer = nullptr;
    UInt32 bufSize = bufferSize * sizeof(short);
    if (AudioQueueAllocateBuffer(queue, bufSize, &buffer) != noErr) {
        AudioQueueDispose(queue, true);
        return;
    }

    GenerateExplosionSound((short*)buffer->mAudioData, bufferSize);
    buffer->mAudioDataByteSize = bufSize;

    AudioQueueEnqueueBuffer(queue, buffer, 0, nullptr);
    AudioQueueStart(queue, nullptr);

    std::this_thread::sleep_for(std::chrono::milliseconds(1050));

    AudioQueueStop(queue, true);
    AudioQueueDispose(queue, true);
}

