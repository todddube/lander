static CTFontRef CreateCTFont(const char* fontFamily, int fontSize, bool bold) {
    // Map font families: "Arial" -> "Helvetica" on macOS
    const char* mappedFamily = fontFamily;
    if (strcmp(fontFamily, "Arial") == 0) mappedFamily = "Helvetica";

    CFStringRef familyName = CFStringCreateWithCString(nullptr, mappedFamily, kCFStringEncodingUTF8);
    // GDI fontSize is cell height; CT uses point size. Approximate conversion.
    CGFloat ptSize = abs(fontSize) * 0.75;

    CTFontRef font = CTFontCreateWithName(familyName, ptSize, nullptr);
    CFRelease(familyName);

    if (bold && font) {
        CTFontRef boldFont = CTFontCreateCopyWithSymbolicTraits(
            font, ptSize, nullptr, kCTFontBoldTrait, kCTFontBoldTrait);
        if (boldFont) {
            CFRelease(font);
            font = boldFont;
        }
    }

    return font;
}

static CGColorRef CreateCGColor(PlatColor color) {
    CGColorSpaceRef cs = CGColorSpaceCreateDeviceRGB();
    CGFloat components[] = {
        ColorR(color) / 255.0, ColorG(color) / 255.0,
        ColorB(color) / 255.0, 1.0
    };
    CGColorRef cgColor = CGColorCreate(cs, components);
    CGColorSpaceRelease(cs);
    return cgColor;
}

void PlatDrawText(PlatContext* ctx, const char* text, int x, int y, int w, int h,
                  PlatColor color, int fontSize, bool bold, const char* fontFamily,
                  PlatTextAlign align) {
    if (!text || !text[0]) return;
    CGContextRef cg = ctx->cgCtx;

    CTFontRef font = CreateCTFont(fontFamily, fontSize, bold);
    CGColorRef cgColor = CreateCGColor(color);

    CFStringRef str = CFStringCreateWithCString(nullptr, text, kCFStringEncodingUTF8);
    CFStringRef attrKeys[] = { kCTFontAttributeName, kCTForegroundColorAttributeName };
    CFTypeRef attrValues[] = { font, cgColor };
    CFDictionaryRef attrs = CFDictionaryCreate(nullptr,
        (const void**)attrKeys, (const void**)attrValues, 2,
        &kCFTypeDictionaryKeyCallBacks, &kCFTypeDictionaryValueCallBacks);
    CFAttributedStringRef attrStr = CFAttributedStringCreate(nullptr, str, attrs);
    CTLineRef line = CTLineCreateWithAttributedString(attrStr);

    // Measure text for alignment
    CGFloat ascent, descent;
    CGFloat textWidth = CTLineGetTypographicBounds(line, &ascent, &descent, nullptr);

    // Calculate X position based on alignment
    CGFloat drawX = x;
    if (align == PlatTextAlign::CENTER) {
        drawX = x + (w - textWidth) / 2.0;
    }

    // Calculate Y position (vertically centered, baseline)
    CGFloat drawY = y + (h + ascent - descent) / 2.0;

    // Un-flip for text rendering: save state, translate to baseline, scale Y by -1
    CGContextSaveGState(cg);
    CGContextTranslateCTM(cg, drawX, drawY);
    CGContextScaleCTM(cg, 1, -1);
    CGContextSetTextPosition(cg, 0, 0);
    CTLineDraw(line, cg);
    CGContextRestoreGState(cg);

    CFRelease(line);
    CFRelease(attrStr);
    CFRelease(attrs);
    CFRelease(str);
    CGColorRelease(cgColor);
    CFRelease(font);
}

void PlatDrawTextXY(PlatContext* ctx, const char* text, int x, int y,
                    PlatColor color, int fontSize, bool bold, const char* fontFamily) {
    if (!text || !text[0]) return;
    CGContextRef cg = ctx->cgCtx;

    CTFontRef font = CreateCTFont(fontFamily, fontSize, bold);
    CGColorRef cgColor = CreateCGColor(color);

    CFStringRef str = CFStringCreateWithCString(nullptr, text, kCFStringEncodingUTF8);
    CFStringRef attrKeys[] = { kCTFontAttributeName, kCTForegroundColorAttributeName };
    CFTypeRef attrValues[] = { font, cgColor };
    CFDictionaryRef attrs = CFDictionaryCreate(nullptr,
        (const void**)attrKeys, (const void**)attrValues, 2,
        &kCFTypeDictionaryKeyCallBacks, &kCFTypeDictionaryValueCallBacks);
    CFAttributedStringRef attrStr = CFAttributedStringCreate(nullptr, str, attrs);
    CTLineRef line = CTLineCreateWithAttributedString(attrStr);

    // Get ascent so we draw from top of text
    CGFloat ascent;
    CTLineGetTypographicBounds(line, &ascent, nullptr, nullptr);
    CGFloat drawY = y + ascent;

    // Un-flip for text rendering
    CGContextSaveGState(cg);
    CGContextTranslateCTM(cg, (CGFloat)x, drawY);
    CGContextScaleCTM(cg, 1, -1);
    CGContextSetTextPosition(cg, 0, 0);
    CTLineDraw(line, cg);
    CGContextRestoreGState(cg);

    CFRelease(line);
    CFRelease(attrStr);
    CFRelease(attrs);
    CFRelease(str);
    CGColorRelease(cgColor);
    CFRelease(font);
}

int PlatMeasureTextWidth(PlatContext* ctx, const char* text, int len,
                         int fontSize, bool bold, const char* fontFamily) {
    (void)ctx;
    if (!text || len <= 0) return 0;

    CTFontRef font = CreateCTFont(fontFamily, fontSize, bold);

    // Create a substring of the specified length
    CFStringRef str = CFStringCreateWithBytes(nullptr,
        (const UInt8*)text, len, kCFStringEncodingUTF8, false);
    CFStringRef attrKeys[] = { kCTFontAttributeName };
    CFTypeRef attrValues[] = { font };
    CFDictionaryRef attrs = CFDictionaryCreate(nullptr,
        (const void**)attrKeys, (const void**)attrValues, 1,
        &kCFTypeDictionaryKeyCallBacks, &kCFTypeDictionaryValueCallBacks);
    CFAttributedStringRef attrStr = CFAttributedStringCreate(nullptr, str, attrs);
    CTLineRef line = CTLineCreateWithAttributedString(attrStr);

    CGFloat width = CTLineGetTypographicBounds(line, nullptr, nullptr, nullptr);

    CFRelease(line);
    CFRelease(attrStr);
    CFRelease(attrs);
    CFRelease(str);
    CFRelease(font);

    return static_cast<int>(width);
}

